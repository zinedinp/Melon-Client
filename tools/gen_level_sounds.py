#!/usr/bin/env python3
"""Writes crates/melon-audio/src/level_sounds/data.rs: the sound each level event plays,
from the decompiled vanilla `LevelEventHandler.java` and `SoundEvents.java`.

    tools/gen_level_sounds.py [path/to/mc-decomp/src/26.3/client]

A case with one `playLocalSound(.., SoundEvents.X, SoundSource.Y, volume,
pitch, ..)` is taken as it is; the few that compute more (sculk charge,
jukeboxes, brushing) are done by hand in `game/sounds.rs`.
"""
import os
import re
import sys

DEFAULT_ROOT = "/mnt/ssd/Programmieren/Pumpkin-Reference/mc-decomp/src/26.3/client"
ROOT = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ROOT
MC = os.path.join(ROOT, "net/minecraft")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "crates/melon-audio/src/level_sounds/data.rs")

# Cases `playLocalSound` isn't plain in, with the sound they come to.
MANUAL = {
    3000: ("END_GATEWAY_SPAWN", "BLOCKS", "10.0", "Pitch::Spread(0.7, 0.14)"),
    3001: ("ENDER_DRAGON_GROWL", "HOSTILE", "64.0", "Pitch::Up(0.8, 0.3)"),
    1051: ("WIND_CHARGE_THROW", "BLOCKS", "0.5", "Pitch::Recip(0.4, 0.8, 0.4)"),
    3007: ("SCULK_SHRIEKER_SHRIEK", "BLOCKS", "2.0", "Pitch::Up(0.6, 0.4)"),
}
# Played without a place, as the player's own ambience.
LOCAL = {1032}


def read(*parts):
    return open(os.path.join(MC, *parts), encoding="utf-8").read()


def pitch(expr):
    e = re.sub(r"\s+", " ", expr.strip())
    e = re.sub(r"(?<=\d)F", "", e)
    if re.fullmatch(r"[\d.]+", e):
        return f"Pitch::Fixed({float(e)!r})"
    m = re.fullmatch(r"\(random\.nextFloat\(\) - random\.nextFloat\(\)\) \* ([\d.]+) \+ ([\d.]+)", e)
    if m:
        return f"Pitch::Spread({float(m[2])!r}, {float(m[1])!r})"
    m = re.fullmatch(r"([\d.]+) \+ \(random\.nextFloat\(\) - random\.nextFloat\(\)\) \* ([\d.]+)", e)
    if m:
        return f"Pitch::Spread({float(m[1])!r}, {float(m[2])!r})"
    m = re.fullmatch(r"random\.nextFloat\(\) \* ([\d.]+) \+ ([\d.]+)", e)
    if m:
        return f"Pitch::Up({float(m[2])!r}, {float(m[1])!r})"
    return None


def main():
    events = dict(re.findall(r'SoundEvent (\w+) = register\w*\("([^"]+)"',
                             read("sounds", "SoundEvents.java")))
    text = read("client", "renderer", "LevelEventHandler.java")
    body = text[text.index("public void levelEvent"):]
    rows, skipped = {}, []
    for labels, block in re.findall(r"((?:case \d+:\s*)+)(.*?)break;", body, re.S):
        numbers = [int(n) for n in re.findall(r"\d+", labels)]
        flat = re.sub(r"\s+", " ", block)
        for n in numbers:
            if n in MANUAL:
                const, src, vol, p = MANUAL[n]
                rows[n] = (events[const], src, vol, p)
        if any(n in MANUAL for n in numbers):
            continue
        found = re.findall(
            r"SoundEvents\.(\w+), SoundSource\.(\w+), ([^,]+?), (.+?), (?:true|false) ?\)", flat)
        if len(found) != 1:
            if "SoundEvents" in flat or "playLocalSound" in flat:
                skipped.append((numbers, len(found)))
            continue
        const, src, vol, p = found[0]
        p = pitch(p)
        if p is None or const not in events or not re.fullmatch(r"[\d.]+F?", vol):
            skipped.append((numbers, "pitch"))
            continue
        for n in numbers:
            rows[n] = (events[const], src, f"{float(vol.rstrip('F'))!r}", p)
    # The three that follow the camera.
    for n, const, vol in ((1023, "WITHER_SPAWN", 1.0), (1028, "ENDER_DRAGON_DEATH", 5.0),
                          (1038, "END_PORTAL_SPAWN", 1.0)):
        rows[n] = (events[const], "HOSTILE", f"{vol!r}", "Pitch::Fixed(1.0)")
    rows[1032] = (events["PORTAL_TRAVEL"], "AMBIENT", "0.25", "Pitch::Up(0.8, 0.4)")
    out = ["//! Generated by tools/gen_level_sounds.py from the decompiled vanilla",
           "//! `LevelEventHandler.java` and `SoundEvents.java`. Do not edit by hand.",
           "", "use super::{LevelSound, Pitch};",
           "use crate::audio::source::SoundSource;", "",
           "#[rustfmt::skip]", "pub static LEVEL_SOUNDS: &[LevelSound] = &["]
    for n in sorted(rows):
        ev, src, vol, p = rows[n]
        out.append(f'    LevelSound {{ event: {n}, sound: "{ev}", source: SoundSource::{src.capitalize()}, '
                   f'volume: {float(vol)!r}, pitch: {p}, local: {str(n in LOCAL).lower()} }},')
    out.append("];")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(out) + "\n")
    print(len(rows), "events; by hand:", skipped)


main()
